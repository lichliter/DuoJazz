import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url);
export async function precacheSource() {
  const paths = ['index.html', 'gallery.html', 'sound.html', 'manifest.webmanifest'];
  for (const dir of ['js', 'css', 'fonts', 'icons', 'images', 'sound']) {
    for (const file of await readdir(new URL(dir, root), { recursive: true })) {
      if (/\.(js|css|woff2|ttf|svg|png|m4a|json)$/.test(file)) paths.push(`${dir}/${file}`);
    }
  }
  paths.sort();
  const hash = createHash('sha256');
  for (const path of [...paths, 'sw.js']) hash.update(path).update(await readFile(new URL(path, root)));
  return `// Generated by node tools/generate-precache.mjs; commit after asset changes.\nconst PRECACHE_VERSION = '${hash.digest('hex').slice(0, 16)}';\nconst PRECACHE_URLS = ${JSON.stringify(paths.map(path => './' + path), null, 2)};\n`;
}
if (process.argv[1] && new URL(process.argv[1], 'file:').href === import.meta.url) {
  await writeFile(new URL('precache.js', root), await precacheSource());
}
