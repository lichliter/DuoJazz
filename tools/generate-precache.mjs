import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url);
const GENERATED_VERSION_PATH = 'js/version.js';

async function releaseInfo() {
  const paths = ['index.html', 'gallery.html', 'sound.html', 'manifest.webmanifest'];
  for (const dir of ['js', 'css', 'fonts', 'icons', 'images', 'sound']) {
    for (const file of await readdir(new URL(dir, root), { recursive: true })) {
      if (/\.(js|css|woff2|ttf|svg|png|m4a|json)$/.test(file)) paths.push(`${dir}/${file}`);
    }
  }
  if (!paths.includes(GENERATED_VERSION_PATH)) paths.push(GENERATED_VERSION_PATH);
  paths.sort();
  const indexHtml = await readFile(new URL('index.html', root), 'utf8');
  const versions = [...indexHtml.matchAll(/\?v=(\d+)/g)].map(m => Number(m[1]));
  const release = versions.length ? Math.max(...versions) : 0;
  const hash = createHash('sha256');
  for (const path of [...paths, 'sw.js']) {
    if (path === GENERATED_VERSION_PATH) continue;
    hash.update(path).update(await readFile(new URL(path, root)));
  }
  const precacheVersion = hash.digest('hex').slice(0, 16);
  return { paths, release, precacheVersion };
}

function formatPrecache({ paths, precacheVersion }) {
  return `// Generated by node tools/generate-precache.mjs; commit after asset changes.\nconst PRECACHE_VERSION = '${precacheVersion}';\nconst PRECACHE_URLS = ${JSON.stringify(paths.map(path => './' + path), null, 2)};\n`;
}

function formatVersion({ release, precacheVersion }) {
  const build = precacheVersion.slice(0, 8);
  const label = release ? `Version ${release} (${build})` : `Build ${build}`;
  return `// Generated by node tools/generate-precache.mjs; commit after asset changes.\nexport const APP_RELEASE = ${release};\nexport const APP_BUILD = '${build}';\nexport const APP_VERSION = '${label}';\n`;
}

export async function releaseAssets() {
  const info = await releaseInfo();
  return {
    ...info,
    precache: formatPrecache(info),
    version: formatVersion(info),
  };
}

export async function precacheSource() {
  return formatPrecache(await releaseInfo());
}

export async function versionSource() {
  return formatVersion(await releaseInfo());
}

if (process.argv[1] && new URL(process.argv[1], 'file:').href === import.meta.url) {
  const assets = await releaseAssets();
  await Promise.all([
    writeFile(new URL(GENERATED_VERSION_PATH, root), assets.version),
    writeFile(new URL('precache.js', root), assets.precache),
  ]);
}
